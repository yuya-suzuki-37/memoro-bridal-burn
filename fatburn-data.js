// ===== プロファイル導出 =====
export function buildProfile(ans){
  const focusAreas = ans.focus && ans.focus.length ? ans.focus : ['waist','hip_leg'];
  const level = (ans.habit==='mid' || ans.habit==='active') ? 'intermediate' : 'beginner';
  const minutes = parseInt(ans.minutes||'20', 10);
  const safety = ans.safety || [];
  const pregnant = safety.includes('preg');
  return { focusAreas, level, minutes, safety, pregnant };
}

// ===== プラン名 =====
import { AREA_LABEL } from './fatburn-engine.js';
export function planTitle(profile){
  const parts = profile.focusAreas.map(a => AREA_LABEL[a]).filter(Boolean);
  const head = parts.length>=3 ? '全身' : parts.slice(0,2).join('・');
  return `${head} 集中燃焼プラン`;
}

